  function close() {
    var el = document.getElementById("terms-backdrop");
    if (el) el.remove();
    document.removeEventListener("keydown", onKey);
    if (lastFocus && lastFocus.focus) { try { lastFocus.focus(); } catch (e) {} }
    lastFocus = null;
  }
  function onKey(e) { if (e.key === "Escape") close(); }

  /* opts.full = true → הנוסח המלא פתוח מראש (לקישור מחלון האישור, שלב 2). */
