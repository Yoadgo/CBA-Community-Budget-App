/* ============================================================================
 *  מילון הגינון — שם אחד לכל מושג, משפט אחד לכל מצב (2026-09-09, גל 1)
 * ----------------------------------------------------------------------------
 *  למה הקובץ הזה קיים:
 *  לפני זה, אותו דבר נקרא בשלושה שמות תלוי במסך. "פתוחים" בסינון של התושב
 *  היה "בטיפול" באריח שמעליו — אותו מספר בדיוק, שני שמות, זה מעל זה.
 *  "דיווח" הפך ל"פנייה" בשורה אחת, ו"מנהל הגינון" הפך ל"הוועד". כל שם כפול
 *  מכריח את המשתמש לתחזק טבלת תרגום בראש בזמן שהוא עובד, וזה — יותר מכל
 *  פיצ'ר בודד — מה שגרם למודול להרגיש מסובך.
 *
 *  שני דברים יושבים כאן, ורק הם:
 *  1. T   — טבלת המונחים. שם אחד לכל מושג, בכל המסכים.
 *  2. state() — **משפט מצב יחיד** למשימה. במקום לחשוף למשתמש ארבעה צירים
 *     בלתי-תלויים (דגל × סגירה × סוג × שלב) ולצפות שירכיב מהם משמעות,
 *     גוזרים כאן פעם אחת משפט אחד, והמסכים רק מציגים אותו.
 *
 *  ⚠️ הצירים עצמם נשארים בנתונים ובשרת בדיוק כפי שהם. הקובץ הזה לא משנה
 *     שום לוגיקה — הוא רק מחליט **מה אומרים** על מצב נתון.
 *
 *  ⚠️ נטען לפני כל מסכי הגינון ב-index.html. כל מסך קורא CBA.gardenLang
 *     בזמן ריצה, ולכן אין תלות בסדר בין המסכים עצמם.
 * ========================================================================== */
(function () {
  var CBA = window.CBA = window.CBA || {};
  var L = CBA.gardenLang = CBA.gardenLang || {};

  /* הערכים שנכתבים בגיליון. אלה **לא** תוויות תצוגה — אלה המפתחות. */
  L.KIND = { REPORT: "דיווח תושב", ROUTINE: "שגרה", MANUAL: "יזום" };

  /* ---------------------------------------------------------- טבלת המונחים */
  L.T = {
    /* מה שהתושב פותח. "פנייה" נמחק — היה שם שני לאותו דבר. */
    report:   "דיווח",
    reports:  "דיווחים",
    /* עבודה מתוכנית העבודה. "חוזרת" נשאר רק בהערות קוד, לא בממשק. */
    routine:  "שגרה",
    manual:   "יזום",
    /* מי מאשר. "הוועד" נמחק — באפליקציה יש תפקיד אחד ושמו מנהל הגינון. */
    manager:  "מנהל הגינון",
    team:     "צוות הגינון",
    /* חתכי הזמן — אותן מילים בכל מסך */
    thisWeek: "השבוע",
    nextWeek: "שבוע הבא",
    later:    "בהמשך",
    unplanned:"לשיבוץ"
  };

  /* "דיווח 7" — ההפניה הקנונית לדיווח של תושב. בלי מספר: "דיווח". */
  L.reportRef = function (repId) {
    return repId ? (L.T.report + " " + repId) : L.T.report;
  };

  /* תווית המסנן הראשון. אותה רשימה נקראה "מחכה לך" לשני התפקידים, אבל
     היא מכילה דברים שונים לגמרי: אצל המנהל — מה שממתין להחלטה שלו; אצל
     הגנן — מה שעוד לא שובץ ומה שהוחזר אליו. אותה מילה לשתי משמעויות היא
     בדיוק מה שהמילון הזה בא לחסל. */
  L.mineLabel = function (isManager) { return isManager ? "להחלטתך" : "לביצוע"; };

  /* ------------------------------------------------------- משפט המצב היחיד */
  /*  state(t, viewer) -> { text, tone }
   *  viewer: "resident" | "gardener" | "manager"
   *  tone:   "done" | "wait" | "warn" | "plan" | "" — לצביעה בלבד, בלי משמעות
   *          נוספת. המסך בוחר איך לצבוע; המילון בוחר מה לומר.
   *
   *  סדר הבדיקות הוא סדר החשיבות: מה שסגור גובר על דגל, ודגל גובר על שיבוץ.
   *  ⚠️ אם משימה נופלת בין הכיסאות, מוחזר השלב הגולמי — עדיף מידע חלקי
   *     נכון מאשר משפט שהומצא.
   */
  L.state = function (t, viewer) {
    t = t || {};
    var v = viewer || "manager";
    var mgr = (v === "manager"), res = (v === "resident");
    var closure = String(t.closure || "").trim();
    var flag    = String(t.flag || "").trim();

    /* 1. אוחד לתוך דיווח אחר */
    if (closure === "אוחד" || t.mergedInto) {
      return { text: "אוחד עם " + L.reportRef(t.mergedInto || ""), tone: "" };
    }
    /* 2. נסגר בלי שבוצעה עבודה — ההחלטה היא התשובה, לא המילה "בוטל" */
    if (closure && closure !== "בוצע") {
      return { text: "לא נפתח טיפול · " + closure, tone: "warn" };
    }
    /* 3. בוצע ונסגר */
    if (closure === "בוצע" || t.stage === "הושלם") {
      return { text: "בוצע", tone: "done" };
    }
    /* 4. בוצע וממתין לאישור */
    if (flag === "ממתין לאישור") {
      return { text: mgr ? "בוצע — ממתין לאישורך"
                         : (res ? "בוצע, ממתין לאישור " + L.T.manager
                                : "בוצע, ממתין לאישור"), tone: "wait" };
    }
    /* 5. הוחזר להשלמה */
    if (flag === "הוחזר להשלמה") {
      return { text: res ? "הוחזר ל" + L.T.team + " להשלמה"
                         : (mgr ? "הוחזר לצוות" : "הוחזר אליך להשלמה"), tone: "warn" };
    }
    /* 6. התושב אמר שלא הושלם */
    if (flag === "דורש בדיקה חוזרת") {
      return { text: res ? "נבדק שוב בעקבות המשוב שלך" : "התושב ביקש בדיקה חוזרת",
               tone: "warn" };
    }
    /* 7. צריך לראות בשטח לפני שמחליטים */
    if (flag === "דורש בדיקה בשטח") {
      return { text: "ממתין לבדיקה בשטח", tone: "wait" };
    }
    /* 8. נגררה לשבוע הבא */
    if (flag === "נגררה") {
      return { text: "נדחה לשבוע הבא", tone: "plan" };
    }
    /* 9. עוד לא נכנס לשום שבוע */
    if (!t.week) {
      return { text: res ? "התקבל, ממתין לשיבוץ"
                         : (mgr ? "ממתין לשיבוץ" : "עוד לא שובץ"), tone: "wait" };
    }
    /* 10. משובץ */
    return { text: "לביצוע " + L.T.thisWeek, tone: "plan" };
  };

  /* תאימות לאחור: resGarden החזיק טבלת FLAG_TEXT משלו. עכשיו היא נגזרת
     מהמשפט, כדי שלא יהיו שני מקומות שמנסחים את אותו דבר. */
  L.flagText = function (flag, viewer) {
    if (!flag) return "";
    var s = L.state({ flag: flag, week: "x" }, viewer || "resident");
    return s.text;
  };
})();
