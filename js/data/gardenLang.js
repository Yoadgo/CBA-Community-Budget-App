/* ============================================================================
 *  מילון הגינון — שם אחד לכל מושג, משפט אחד לכל מצב (2026-09-09, גל 1)
 * ----------------------------------------------------------------------------
 *  למה הקובץ הזה קיים:
 *  לפני זה, אותו דבר נקרא בשלושה שמות תלוי במסך. "פתוחים" בסינון של התושב
 *  היה "בטיפול" באריח שמעליו — אותו מספר בדיוק, שני שמות, זה מעל זה.
 *  "דיווח" הפך ל"פנייה" בשורה אחת, ו"מנהל הגינון" הפך ל"הוועד". כל שם כפול
 *  מכריח את המשתמש לתחזק טבלת תרגום בראש בזמן שהוא עובד, וזה — יותר מכל
 *  פיצ'ר בודד — מה שגרם למודול להרגיש מסובך.
 *
 *  שני דברים יושבים כאן, ורק הם:
 *  1. T   — טבלת המונחים. שם אחד לכל מושג, בכל המסכים.
 *  2. state() — **משפט מצב יחיד** למשימה. במקום לחשוף למשתמש ארבעה צירים
 *     בלתי-תלויים (דגל × סגירה × סוג × שלב) ולצפות שירכיב מהם משמעות,
 *     גוזרים כאן פעם אחת משפט אחד, והמסכים רק מציגים אותו.
 *
 *  ⚠️ הצירים עצמם נשארים בנתונים ובשרת בדיוק כפי שהם. הקובץ הזה לא משנה
 *     שום לוגיקה — הוא רק מחליט **מה אומרים** על מצב נתון.
 *
 *  ⚠️ נטען לפני כל מסכי הגינון ב-index.html. כל מסך קורא CBA.gardenLang
 *     בזמן ריצה, ולכן אין תלות בסדר בין המסכים עצמם.
 * ========================================================================== */
(function () {
  var CBA = window.CBA = window.CBA || {};
  var L = CBA.gardenLang = CBA.gardenLang || {};

  /* הערכים שנכתבים בגיליון. אלה **לא** תוויות תצוגה — אלה המפתחות. */
  L.KIND = { REPORT: "דיווח תושב", ROUTINE: "שגרה", MANUAL: "יזום" };

  /* ---------------------------------------------------------- טבלת המונחים */
  L.T = {
    /* מה שהתושב פותח. "פנייה" נמחק — היה שם שני לאותו דבר. */
    report:   "דיווח",
    reports:  "דיווחים",
    /* עבודה מתוכנית העבודה. "חוזרת" נשאר רק בהערות קוד, לא בממשק. */
    routine:  "שגרה",
    manual:   "יזום",
    /* מי מאשר. "הוועד" נמחק — באפליקציה יש תפקיד אחד ושמו מנהל הגינון. */
    manager:  "מנהל הגינון",
    team:     "צוות הגינון",
    /* מי שפתח תקלה מהשטח (22.9) — התווית על הכרטיס, ליד "מנהל". */
    gardener: "גנן",
    /* חתכי הזמן — אותן מילים בכל מסך */
    thisWeek: "השבוע",
    nextWeek: "שבוע הבא",
    later:    "בהמשך",
    unplanned:"לשיבוץ"
  };

  /* 🔴 22.9 (בקשת יועד) — **הקטגוריה המאוחדת.** "מדשאות" ו"השקיה / ממטרות"
     הפכו לקטגוריה אחת. השם כאן הוא המחרוזת שנכתבת בנתונים; המיגרציה בשרת
     (gardenMergeLawnWater_) ממירה אליו את שני השמות הישנים. */
  L.CAT_LAWN_WATER = "מדשאות, השקיה וממטרות";

  /* קפסולות כותרת-מהירה לפי קטגוריה — **מקור אחד** לטופס התושב ולטופס
     הצוות (22.9, בקשת יועד: "פריסטים בדומה לדיווח תושב"). עד היום הרשימה
     ישבה בתוך resGarden.js, והעתק שני בטופס הצוות היה מתחיל לסטות ביום
     הראשון. המפתחות הם שמות הקטגוריות בדיוק כפי שהם בגיליון. */
  L.TITLE_PICKS = {};
  L.TITLE_PICKS[L.CAT_LAWN_WATER] = ["מדשאה יבשה", "עשב גבוה מדי", "ראש ממטרה שבור",
                                     "דליפת מים", "נראה שההשקייה לא עובדת"];
  L.TITLE_PICKS["עצים"] = ["ענף שבור/מסוכן", "עץ נוטה/מתנדנד", "עץ יבש"];
  L.TITLE_PICKS["שיחים / גיזום"] = ["שיח חוסם מעבר", "צריך גיזום", "ענפים פרוצים"];
  L.TITLE_PICKS["עשבייה / קרקע"] = ["עשביה שוטה", "קוצים"];
  L.TITLE_PICKS["ניקיון גינון / גזם"] = ["גזם לא פונה", "אשפה/לכלוך", "עלים נערמים"];
  L.TITLE_PICKS["ערוגות / שתילות"] = ["שתיל פגוע/יבש", "ערוגה מוזנחת", "חסר שתילים"];
  /* שני השמות הישנים ממשיכים להציע את אותן קפסולות עד שהמיגרציה תרוץ —
     אחרת בחלון שבין הדיפלוי להרצה הטופס מאבד את ההצעות. */
  L.TITLE_PICKS["מדשאות"] = L.TITLE_PICKS[L.CAT_LAWN_WATER];
  L.TITLE_PICKS["השקיה / ממטרות"] = L.TITLE_PICKS[L.CAT_LAWN_WATER];

  /* ==========================================================================
   *  🔴 "נגררה" בשתי רמות — הגדרה אחת לכל האפליקציה   (22.9.2026)
   * --------------------------------------------------------------------------
   *  הכרעת יועד (אפיון מסך הנתונים, סעיף 4 + סעיף 8):
   *  · **מושג אחד.** "נגררה" מחליף את "בעיכוב" — מה שכתוב על הכרטיס
   *    ומה שנספר במסך הנתונים הם אותו דבר, כי שניהם קוראים לפונקציה הזאת.
   *  · **נמדד בשבועות, לא בפעמים.** המרחק בין השבוע המקורי
   *    (`firstWeek || week`) לבין הגדול מבין השבוע הנוכחי והשבוע שאליו
   *    המשימה נדחתה. כך גם משימה שהשבוע שלה פשוט עבר נחשבת — עד היום
   *    היא לא קיבלה שום תג, למרות שזה בדיוק עיכוב.
   *  · **שבוע אחד = ורוד (level 1), שבועיים ומעלה = אדום (level 2).**
   *  · דחייה ידנית לשבוע הבא הופכת לוורוד **מיד** — המשימה כבר לא בשבוע שלה.
   *  🔑 אין שדה חדש בנתונים. `firstWeek` נכתב כבר בכל דחייה (gardenFsTask).
   *  ⚠️ בלי תג: משימה סגורה, משימה בלי שבוע (נמדדת בגיל ולא בתג), ומשימה
   *     שהגנן סימן ומחכה לאישור — העבודה נעשתה, והיא נספרת ב"ממתינות
   *     לאישורך" ולא כגרירה.
   * ======================================================================== */
  function wkDate(key) {
    var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(key || "").trim());
    return m ? new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]), 12, 0, 0) : null;
  }
  function pad2(x) { return (x < 10 ? "0" : "") + x; }
  /** מפתח השבוע (יום ראשון, YYYY-MM-DD) של תאריך. בלי ארגומנט — השבוע הנוכחי. */
  L.weekOf = function (d) {
    var x = d ? new Date(d.getTime ? d.getTime() : d) : new Date();
    if (isNaN(x.getTime())) return "";
    x.setHours(12, 0, 0, 0);
    x.setDate(x.getDate() - x.getDay());
    return x.getFullYear() + "-" + pad2(x.getMonth() + 1) + "-" + pad2(x.getDate());
  };
  /** כמה שבועות מ-a עד b (שני מפתחות שבוע). */
  L.weeksBetween = function (a, b) {
    var da = wkDate(a), db = wkDate(b);
    if (!da || !db) return 0;
    return Math.round((db.getTime() - da.getTime()) / (7 * 86400000));
  };
  /** "שבועיים" / "3 שבועות". */
  L.weeksText = function (n) {
    return n === 1 ? "שבוע" : n === 2 ? "שבועיים" : n + " שבועות";
  };
  /** drag(t, curWeek) -> { weeks, level: 0|1|2, text } */
  L.drag = function (t, curWeek) {
    var none = { weeks: 0, level: 0, text: "" };
    t = t || {};
    if (String(t.closure || "").trim()) return none;
    if (String(t.flag || "").trim() === "ממתין לאישור") return none;
    var week = String(t.week || "").trim();
    if (!week) return none;
    var orig = String(t.firstWeek || "").trim() || week;
    var cur = curWeek || L.weekOf();
    var end = week > cur ? week : cur;
    var n = L.weeksBetween(orig, end);
    if (n <= 0) return none;
    return { weeks: n, level: n >= 2 ? 2 : 1,
             text: n >= 2 ? "נגררה " + L.weeksText(n) : "נגררה" };
  };

  /* ---------------------------------------------- קטגוריה -> סמליל וצבע
     🔑 **העתק מרכזי** של הטבלה ב-gardenTasks.js וב-resGarden.js
     (22.9.2026, מסך הנתונים). מסך המשימות קורא מכאן כשהקובץ טעון; הצבעים
     הם המשתנים --c-<key> ב-garden.css. ההתאמה לפי מילת מפתח ולא מחרוזת
     מדויקת, כדי ששם קטגוריה ישן ("מדשאות") ימשיך להיצבע נכון. */
  L.CATS = [
    { key: "lawn",  match: /דשא|מדשא/,   ico: "lawn"  },
    { key: "water", match: /השקי|ממטר/,  ico: "water" },
    { key: "tree",  match: /^עצים|עץ/,    ico: "tree"  },
    { key: "prune", match: /גיזום|שיח/,  ico: "prune" },
    { key: "weed",  match: /עשבי|קרקע/,  ico: "weed"  },
    { key: "clean", match: /ניקיון|גזם/, ico: "clean" },
    { key: "bed",   match: /ערוג|שתיל/,  ico: "bed"   }
  ];
  L.catOf = function (name) {
    for (var i = 0; i < L.CATS.length; i++) if (L.CATS[i].match.test(name || "")) return L.CATS[i];
    return { key: "lawn", ico: "lawn" };
  };

  /* "דיווח 7" — ההפניה הקנונית לדיווח של תושב. בלי מספר: "דיווח". */
  L.reportRef = function (repId) {
    return repId ? (L.T.report + " " + repId) : L.T.report;
  };

  /* תווית המסנן הראשון. אותה רשימה נקראה "מחכה לך" לשני התפקידים, אבל
     היא מכילה דברים שונים לגמרי: אצל המנהל — מה שממתין להחלטה שלו; אצל
     הגנן — מה שעוד לא שובץ ומה שהוחזר אליו. אותה מילה לשתי משמעויות היא
     בדיוק מה שהמילון הזה בא לחסל. */
  L.mineLabel = function (isManager) { return isManager ? "להחלטתך" : "לביצוע"; };

  /* ------------------------------------------------------- משפט המצב היחיד */
  /*  state(t, viewer) -> { text, tone }
   *  viewer: "resident" | "gardener" | "manager"
   *  tone:   "done" | "wait" | "warn" | "plan" | "" — לצביעה בלבד, בלי משמעות
   *          נוספת. המסך בוחר איך לצבוע; המילון בוחר מה לומר.
   *
   *  סדר הבדיקות הוא סדר החשיבות: מה שסגור גובר על דגל, ודגל גובר על שיבוץ.
   *  ⚠️ אם משימה נופלת בין הכיסאות, מוחזר השלב הגולמי — עדיף מידע חלקי
   *     נכון מאשר משפט שהומצא.
   */
  L.state = function (t, viewer) {
    t = t || {};
    var v = viewer || "manager";
    var mgr = (v === "manager"), res = (v === "resident");
    var closure = String(t.closure || "").trim();
    var flag    = String(t.flag || "").trim();

    /* 1. אוחד לתוך דיווח אחר */
    if (closure === "אוחד" || t.mergedInto) {
      return { text: "אוחד עם " + L.reportRef(t.mergedInto || ""), tone: "" };
    }
    /* 2. נסגר בלי שבוצעה עבודה — ההחלטה היא התשובה, לא המילה "בוטל" */
    if (closure && closure !== "בוצע") {
      return { text: "לא נפתח טיפול · " + closure, tone: "warn" };
    }
    /* 3. בוצע ונסגר */
    if (closure === "בוצע" || t.stage === "הושלם") {
      return { text: "בוצע", tone: "done" };
    }
    /* 4. בוצע וממתין לאישור */
    if (flag === "ממתין לאישור") {
      return { text: mgr ? "בוצע — ממתין לאישורך"
                         : (res ? "בוצע, ממתין לאישור " + L.T.manager
                                : "בוצע, ממתין לאישור"), tone: "wait" };
    }
    /* 5. הוחזר להשלמה */
    if (flag === "הוחזר להשלמה") {
      return { text: res ? "הוחזר ל" + L.T.team + " להשלמה"
                         : (mgr ? "הוחזר לצוות" : "הוחזר אליך להשלמה"), tone: "warn" };
    }
    /* 6. התושב אמר שלא הושלם */
    if (flag === "דורש בדיקה חוזרת") {
      return { text: res ? "נבדק שוב בעקבות המשוב שלך" : "התושב ביקש בדיקה חוזרת",
               tone: "warn" };
    }
    /* 7. צריך לראות בשטח לפני שמחליטים */
    if (flag === "דורש בדיקה בשטח") {
      return { text: "ממתין לבדיקה בשטח", tone: "wait" };
    }
    /* 8. נגררה לשבוע הבא */
    if (flag === "נגררה") {
      return { text: "נדחה לשבוע הבא", tone: "plan" };
    }
    /* 9. עוד לא נכנס לשום שבוע */
    if (!t.week) {
      return { text: res ? "התקבל, ממתין לשיבוץ"
                         : (mgr ? "ממתין לשיבוץ" : "עוד לא שובץ"), tone: "wait" };
    }
    /* 10. משובץ */
    return { text: "לביצוע " + L.T.thisWeek, tone: "plan" };
  };

  /* תאימות לאחור: resGarden החזיק טבלת FLAG_TEXT משלו. עכשיו היא נגזרת
     מהמשפט, כדי שלא יהיו שני מקומות שמנסחים את אותו דבר. */
  L.flagText = function (flag, viewer) {
    if (!flag) return "";
    var s = L.state({ flag: flag, week: "x" }, viewer || "resident");
    return s.text;
  };
})();
